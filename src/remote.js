/**
 * Bash scripts that run on the server, generated as plain strings (sent over ssh to `bash -s`).
 * Every value is single-quoted with shq(). Scripts report results on stdout as marker lines,
 * `@@dk key=value`, which the CLI parses; everything else is streamed to the user as-is.
 *
 * Server state lives in /etc/dockeriser (mode 700, root), or ~/.dockeriser when the user is not root
 * and has no passwordless sudo:
 *   <key>.previous / <key>.current   image IDs, for rollback
 *   <key>.images                     "<dk-ref> <pulled-ref|->" lines: images dockeriser put there
 *   <name>.env / <name>.env.previous run-mode env files (600)
 *   puller.json                      read-only registry key (transfer "pull" only, 600)
 */

import { shq } from './ssh.js';

export const STATE_DIR = '/etc/dockeriser';
export const MARK = '@@dk';

/** File-name-safe key for an image target (container name or tagAs). */
export function stateKey(value) {
  return String(value).replace(/[^A-Za-z0-9_.-]+/g, '_');
}

/** dockeriser's own tag for an image on the server: <repository>:dk-<12 hex of the digest>. */
export function dkRef(repository, digest) {
  return `${repository}:dk-${String(digest).replace(/^sha256:/, '').slice(0, 12)}`;
}

/** Common start of every script: picks how to run docker and where state lives. */
export function prelude({ stateDir = STATE_DIR, needDocker = true } = {}) {
  return `#!/usr/bin/env bash
# generated by dockeriser
set -u
mark() { echo "${MARK} $*"; }
if [ "$(id -u)" = 0 ]; then S=""; STATE=${shq(stateDir)}
elif sudo -n true 2>/dev/null; then S="sudo -n"; STATE=${shq(stateDir)}
else S=""; STATE="$HOME/.dockeriser"; fi
if [ -z "$S" ] && [ "$(id -u)" != 0 ]; then D="docker"; else D="$S docker"; fi
${needDocker ? `if ! $D info >/dev/null 2>&1; then
  mark error=no-docker
  echo "docker is not installed or not usable by $(id -un) on this server." >&2
  exit 20
fi` : ''}
$S mkdir -p "$STATE" && $S chmod 700 "$STATE"
get() { $S cat "$STATE/$1" 2>/dev/null || true; }
put() { printf '%s\\n' "$2" | $S tee "$STATE/$1" >/dev/null; }
disk_free() { local root; root=$($D info --format '{{.DockerRootDir}}' 2>/dev/null); [ -d "$root" ] || root=/; df -Pk "$root" | awk 'NR==2 {print $4}'; }
`;
}

/**
 * Quick look at the server: docker version, which dk refs it already has, free disk.
 * @param {{refs?: string[], stateDir?: string}} [opts]
 */
export function probeScript({ refs = [], stateDir } = {}) {
  let s = prelude({ stateDir, needDocker: false });
  s += `mark user="$(id -un)" sudo="\${S:-none}" arch="$(uname -m)"
if $D info >/dev/null 2>&1; then mark docker="$($D version --format '{{.Server.Version}}' 2>/dev/null)"; else mark docker=missing; exit 0; fi
mark disk_kb="$(disk_free)"
`;
  refs.forEach((ref, i) => {
    s += `if id=$($D image inspect --format '{{.Id}}' ${shq(ref)} 2>/dev/null); then mark have=${i} id="$id"; else mark missing=${i}; fi\n`;
  });
  return s;
}

/** Install Docker with the official convenience script. */
export function installDockerScript() {
  return `${prelude({ needDocker: false })}if $D info >/dev/null 2>&1; then mark docker=present; exit 0; fi
command -v curl >/dev/null 2>&1 || { echo "curl is missing on the server" >&2; exit 21; }
curl -fsSL https://get.docker.com | $S sh || exit 22
$S systemctl enable --now docker >/dev/null 2>&1 || true
mark docker="$($S docker version --format '{{.Server.Version}}' 2>/dev/null)"
`;
}

/**
 * Store the read-only registry key from stdin and log docker in with it (transfer "pull").
 * Run as `bash -c <script>` with the key on stdin; the key never appears in a command line.
 * @param {{registryHost: string, stateDir?: string}} opts
 */
export function installPullerKeyScript({ registryHost, stateDir }) {
  return `${prelude({ stateDir })}umask 077
$S tee "$STATE/puller.json" >/dev/null || exit 23
$S chmod 600 "$STATE/puller.json"
[ -z "$S" ] || $S chown root:root "$STATE/puller.json"
if $S cat "$STATE/puller.json" | $D login -u _json_key --password-stdin ${shq(`https://${registryHost}`)} >/dev/null; then mark login=ok; else mark login=failed; exit 24; fi
`;
}

/**
 * Check docker login to the registry works without downloading anything: asking for a tag that
 * cannot exist answers "not found" when signed in and "denied/unauthorized" when not.
 * @param {{probeRef: string, stateDir?: string}} opts
 */
export function registryCheckScript({ probeRef, stateDir }) {
  return `${prelude({ stateDir })}out=$($D manifest inspect ${shq(probeRef)} 2>&1); rc=$?
if [ $rc = 0 ] || echo "$out" | grep -qiE 'not found|manifest unknown|no such manifest'; then mark registry=ok
else mark registry=denied; echo "$out" | tail -n 3 >&2; fi
`;
}

/** Shell lines that write base64 data into a 600 file without it ever touching a command line. */
function writeSecretFile(target, base64) {
  return `( umask 077; printf '%s' ${shq(base64)} | base64 -d | $S tee "${target}.new" >/dev/null ) && $S chmod 600 "${target}.new"`;
}

/**
 * Bring every item's image into place on the server and set NEW_<i> to its image ID.
 * transfer "pull": docker pull by digest, then tag with the dk ref. transfer "ssh": the image was
 * loaded beforehand (`docker load`), tagged with the dk ref. Rollback: NEW_<i> is the recorded previous ID.
 */
function obtainSection(items, { transfer, rollback }) {
  let s = '';
  items.forEach((it, i) => {
    const key = shq(stateKey(it.key));
    if (rollback) {
      s += `NEW_${i}=$(get ${shq(`${stateKey(it.key)}.previous`)})
if [ -z "$NEW_${i}" ] || ! $D image inspect "$NEW_${i}" >/dev/null 2>&1; then mark error=no-previous item=${i}; echo "No previous image recorded on the server for ${it.label}." >&2; exit 12; fi
`;
      return;
    }
    if (transfer === 'pull') {
      s += `echo "pulling ${it.label}..."
if ! $D pull ${shq(it.pullRef)}; then mark error=pull-failed item=${i}; exit 11; fi
$D tag ${shq(it.pullRef)} ${shq(it.dkRef)} || exit 11
`;
    }
    s += `if ! NEW_${i}=$($D image inspect --format '{{.Id}}' ${shq(it.dkRef)} 2>/dev/null); then mark error=image-missing item=${i}; echo "${it.dkRef} is not on the server." >&2; exit 11; fi
mark item=${i} new="$NEW_${i}"
`;
  });
  return s;
}

/** Keep the current and previous image per item; remove older images dockeriser put there. */
function cleanupSection(items) {
  let s = `mark disk_before_cleanup_kb="$(disk_free)"\n`;
  items.forEach((it, i) => {
    const list = `"$STATE/"${shq(`${stateKey(it.key)}.images`)}`;
    const entry = `${it.dkRef} ${it.pullRef && it.transfer === 'pull' ? it.pullRef : '-'}`;
    s += `{ get ${shq(`${stateKey(it.key)}.images`)}; ${it.dkRef ? `echo ${shq(entry)};` : ''} } | awk 'NF && !seen[$1]++' > /tmp/dk-list.$$
: > /tmp/dk-keep.$$
while read -r ref pulled; do
  id=$($D image inspect --format '{{.Id}}' "$ref" 2>/dev/null) || continue
  if [ "$id" = "$NEW_${i}" ] || [ "$id" = "\${PREV_${i}:-none}" ]; then echo "$ref $pulled" >> /tmp/dk-keep.$$; continue; fi
  echo "removing old image $ref"
  $D image rm "$ref" >/dev/null 2>&1 || { echo "$ref $pulled" >> /tmp/dk-keep.$$; continue; }
  [ "$pulled" = "-" ] || $D image rm "$pulled" >/dev/null 2>&1 || true
done < /tmp/dk-list.$$
$S tee ${list} < /tmp/dk-keep.$$ >/dev/null
rm -f /tmp/dk-list.$$ /tmp/dk-keep.$$
`;
  });
  return s;
}

/** Record previous/current image IDs after a good deploy or rollback. */
function recordSection(items) {
  return items
    .map((it, i) => {
      const key = stateKey(it.key);
      return `[ -z "\${PREV_${i}:-}" ] || put ${shq(`${key}.previous`)} "$PREV_${i}"\nput ${shq(`${key}.current`)} "$NEW_${i}"\n`;
    })
    .join('');
}

/** Print the last log lines between markers so the CLI can capture them. */
function logsBlock(cmd) {
  return `mark logs-begin\n${cmd} 2>&1 | tail -n 50\nmark logs-end\n`;
}

/**
 * The deploy (or rollback) script.
 * @param {object} opts
 * @param {'run'|'compose'|'load-only'} opts.mode
 * @param {'ssh'|'pull'} opts.transfer
 * @param {Array<{label: string, key: string, dkRef: string, pullRef?: string, tagAs?: string, services?: string[]}>} opts.items
 * @param {boolean} [opts.rollback]
 * @param {object} [opts.run] run mode: {name, ports: string[], envBase64?: string|null, useEnv?: boolean, healthUrl?, waitSec?: number, healthTimeoutSec?: number}
 * @param {object} [opts.compose] compose mode: {dir, file?, project?, timeoutSec?: number}
 * @param {string|null} [opts.then] Command run on the server (by the ssh user, in bash) after the images are in place.
 * @param {string} [opts.stateDir]
 */
export function deployScript({ mode, transfer, items, rollback = false, run = {}, compose = {}, then = null, stateDir }) {
  let s = prelude({ stateDir });
  s += `mark disk_before_kb="$(disk_free)"\n`;
  items.forEach((it) => (it.transfer = transfer));
  s += obtainSection(items, { transfer, rollback });

  if (mode === 'run') {
    const name = shq(run.name);
    const envPath = `$STATE/${stateKey(run.name)}.env`;
    const ports = (run.ports || []).map((p) => `-p ${shq(p)}`).join(' ');
    s += `PREV_0=$($D inspect --format '{{.Image}}' ${name} 2>/dev/null || true)
mark previous="$PREV_0"
`;
    if (run.envBase64 && !rollback) {
      s += `${writeSecretFile(envPath, run.envBase64)} || exit 13
[ ! -f "${envPath}" ] || $S cp -p "${envPath}" "${envPath}.previous"
$S mv "${envPath}.new" "${envPath}"
`;
    }
    const envFlag = (file) => (run.useEnv ? `--env-file "${file}"` : '');
    s += `start() { # $1 image id, $2 env file
  $D rm -f ${name} >/dev/null 2>&1 || true
  $D run -d --name ${name} --restart unless-stopped --label dockeriser=1 ${ports} ${run.useEnv ? '${2:+--env-file "$2"}' : ''} "$1" >/dev/null
}
healthy() {
  sleep ${Number(run.waitSec ?? 10)}
  [ "$($D inspect --format '{{.State.Running}}' ${name} 2>/dev/null)" = true ] || { echo "the container is not running"; return 1; }
  [ "$($D inspect --format '{{.RestartCount}}' ${name} 2>/dev/null)" = 0 ] || { echo "the container keeps restarting"; return 1; }
`;
    if (run.healthUrl) {
      s += `  local end=$(( $(date +%s) + ${Number(run.healthTimeoutSec ?? 60)} ))
  while :; do
    if command -v curl >/dev/null 2>&1; then curl -fsS -o /dev/null --max-time 5 ${shq(run.healthUrl)} && return 0
    else wget -q -O /dev/null -T 5 ${shq(run.healthUrl)} && return 0; fi
    [ "$(date +%s)" -lt "$end" ] || { echo "${run.healthUrl} did not answer OK"; return 1; }
    sleep 3
  done
`;
    }
    s += `  return 0
}
echo "starting ${run.name}..."
ENV_NOW=""; [ -f "${envPath}" ] && ENV_NOW="${envPath}"
${run.useEnv ? '' : 'ENV_NOW=""'}
if ! start "$NEW_0" "$ENV_NOW"; then why="docker run failed"; ok=0; else ok=1; fi
if [ $ok = 1 ]; then why=$(healthy) || ok=0; fi
if [ $ok = 0 ]; then
  mark health=failed reason="$why"
  ${logsBlock(`$D logs --tail 50 ${name}`)}
  if [ -n "$PREV_0" ] && [ "$PREV_0" != "$NEW_0" ]; then
    echo "rolling back to the previous image..."
    ENV_OLD="$ENV_NOW"; [ -f "${envPath}.previous" ] && ENV_OLD="${envPath}.previous"
    ${run.useEnv ? '' : 'ENV_OLD=""'}
    if start "$PREV_0" "$ENV_OLD"; then mark rolledback=1; else mark rolledback=failed; fi
    ${envFlag('') ? '' : ''}
  else
    mark rolledback=0
  fi
  exit 10
fi
mark health=ok
`;
  } else {
    items.forEach((it, i) => {
      s += `PREV_${i}=$($D image inspect --format '{{.Id}}' ${shq(it.tagAs)} 2>/dev/null || true)
mark item=${i} previous="$PREV_${i}"
$D tag "$NEW_${i}" ${shq(it.tagAs)} || exit 14
`;
    });
    if (mode === 'compose') {
      const services = [...new Set(items.flatMap((it) => it.services || []))];
      const svc = services.map(shq).join(' ');
      const dc = `$D compose${compose.file ? ` -f ${shq(compose.file)}` : ''}${compose.project ? ` -p ${shq(compose.project)}` : ''}`;
      s += `cd ${shq(compose.dir)} || { mark error=no-compose-dir; exit 15; }
dc() { ${dc} "$@"; }
wait_healthy() {
  local end=$(( $(date +%s) + ${Number(compose.timeoutSec ?? 120)} )) all st cid
  while :; do
    all=1
    for svc in ${svc}; do
      cids=$(dc ps -q "$svc" 2>/dev/null)
      [ -n "$cids" ] || { all=0; continue; }
      for cid in $cids; do
        st=$($D inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null)
        case "$st" in
          healthy|running) ;;
          unhealthy|exited|dead) echo "$svc is $st"; return 1 ;;
          *) all=0 ;;
        esac
      done
    done
    [ $all = 1 ] && return 0
    [ "$(date +%s)" -lt "$end" ] || { echo "services not healthy after ${Number(compose.timeoutSec ?? 120)}s"; return 1; }
    sleep 3
  done
}
echo "restarting ${services.join(', ')}..."
ok=1; why=""
dc up -d --no-deps ${svc} || { ok=0; why="docker compose up failed"; }
if [ $ok = 1 ]; then why=$(wait_healthy) || ok=0; fi
if [ $ok = 0 ]; then
  mark health=failed reason="$why"
  ${logsBlock(`dc logs --no-color --tail 50 ${svc}`)}
  rolled=0
${items.map((it, i) => `  if [ -n "$PREV_${i}" ] && [ "$PREV_${i}" != "$NEW_${i}" ]; then $D tag "$PREV_${i}" ${shq(it.tagAs)} && rolled=1; fi`).join('\n')}
  if [ $rolled = 1 ]; then echo "rolling back to the previous images..."; if dc up -d --no-deps ${svc}; then mark rolledback=1; else mark rolledback=failed; fi
  else mark rolledback=0; fi
  exit 10
fi
mark health=ok
`;
    } else {
      s += `mark health=skipped\n`;
    }
  }
  s += recordSection(items);
  if (then) {
    s += `echo ${shq(`running: ${then}`)}
if bash -c ${shq(then)}; then mark then=ok; else rc=$?; mark then=failed code=$rc; exit 16; fi
`;
  }
  if (!rollback) s += cleanupSection(items);

  s += `mark disk_after_kb="$(disk_free)"\nmark result=ok\n`;
  return s;
}

/**
 * Remote command for `dockeriser logs`.
 * @param {{mode: string, name?: string, compose?: {dir: string, file?: string, project?: string}, services?: string[], tail?: number, follow?: boolean}} opts
 */
export function logsScript({ mode, name, compose = {}, services = [], tail = 100, follow = false, stateDir }) {
  const f = follow ? ' -f' : '';
  let s = prelude({ stateDir });
  if (mode === 'compose') {
    s += `cd ${shq(compose.dir)} || exit 15\n$D compose${compose.file ? ` -f ${shq(compose.file)}` : ''}${compose.project ? ` -p ${shq(compose.project)}` : ''} logs --no-color --tail ${Number(tail)}${f} ${services.map(shq).join(' ')}\n`;
  } else {
    s += `$D logs --tail ${Number(tail)}${f} ${shq(name)}\n`;
  }
  return s;
}

/** Remote command that runs `docker load` reading the archive from stdin. */
export function loadCommand({ stateDir } = {}) {
  return remoteBash(`${prelude({ stateDir })}$D load`);
}

/**
 * A remote command that runs `script` with bash while leaving stdin free for data (an image archive,
 * a key). The script travels base64-encoded, so the ssh argument holds no quotes or newlines and
 * survives Windows argument quoting, ssh and the remote login shell unchanged.
 * @param {string} script
 */
export function remoteBash(script) {
  const b64 = Buffer.from(script).toString('base64');
  return `t=$(mktemp) && echo ${b64} | base64 -d > $t && bash $t; r=$?; rm -f $t; exit $r`;
}

/**
 * Parse marker lines out of script output.
 * @param {string} stdout
 * @returns {{marks: Array<Record<string, string>>, logs: string[], values: Record<string, string>}}
 */
export function parseMarks(stdout) {
  const marks = [];
  const logs = [];
  const values = {};
  let inLogs = false;
  for (const line of stdout.split(/\r?\n/)) {
    if (line.startsWith(`${MARK} `)) {
      const rec = {};
      for (const m of line.slice(MARK.length + 1).matchAll(/([A-Za-z_][\w-]*)=("([^"]*)"|\S*)/g)) rec[m[1]] = m[3] ?? m[2];
      if ('logs-begin' in rec || line.includes('logs-begin')) inLogs = true;
      else if (line.includes('logs-end')) inLogs = false;
      marks.push(rec);
      if (rec.item === undefined) Object.assign(values, rec);
      continue;
    }
    if (inLogs) logs.push(line);
  }
  return { marks, logs, values };
}

/** Per-item values (by `item=<i>` markers). */
export function itemMarks(marks, i) {
  return Object.assign({}, ...marks.filter((m) => m.item === String(i)));
}
